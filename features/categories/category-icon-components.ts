export type CategoryIconName = keyof typeof categoryIconComponents;

function isCategoryIconName(name: string): name is CategoryIconName {
  return Object.hasOwn(categoryIconComponents, name);
}

export function resolveCategoryIconName(name: string): CategoryIconName | undefined {
  if (isCategoryIconName(name)) return name;
  return name === "code" ? "Code2" : undefined;
}

export function CategoryIcon({ name, fallback = "Code2", ...props }: LucideProps & {
  name: string;
  fallback?: CategoryIconName;
}) {
  return createElement(categoryIconComponents[resolveCategoryIconName(name) ?? fallback], props);
}
